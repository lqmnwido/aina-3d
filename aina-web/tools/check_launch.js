import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
import {LAUNCH_ACK,LANDING_MESSAGE} from '../src/launch.js';
import {mkdir} from 'node:fs/promises';
await mkdir('qa',{recursive:true});
const browser=await chromium.launch({headless:true,args:['--use-angle=d3d11']});
try{
  const page=await browser.newPage({viewport:{width:1440,height:1000}});const errors=[],spoken=[];let chats=0,releaseAck,ackReceived;
  await page.addInitScript(()=>{
    window.playedRates=[];window.jetpackStarts=[];window.videoCoverGates=[];
    const start=AudioBufferSourceNode.prototype.start;
    AudioBufferSourceNode.prototype.start=function(...args){window.playedRates.push(this.playbackRate.value);if(this.loop)window.jetpackStarts.push(this.context.currentTime);return start.apply(this,args);};
    const original=HTMLMediaElement.prototype.play;let rejectFirst=true;
    HTMLMediaElement.prototype.play=function(){if(this.src.includes('v2t-v4-4.mp4'))window.videoCoverGates.push(document.querySelector('.launch-trail')?.dataset.covered==='true');if(rejectFirst&&this.src.includes('v2t-v4-4.mp4')){rejectFirst=false;return Promise.reject(new DOMException('Simulated audible autoplay restriction','NotAllowedError'));}return original.call(this);};
  });
  const acknowledgement=new Promise(resolve=>{ackReceived=resolve;});
  let holdAck=true;
  page.on('pageerror',e=>errors.push(e.message));
  page.on('console',message=>{if(message.type()==='error'&&/Shader Error|VALIDATE_STATUS|compile shader/i.test(message.text()))errors.push(message.text());});
  await page.route('**/api/config',route=>route.fulfill({contentType:'application/json',body:'{"configured":true,"ttsConfigured":true,"chatConfigured":true,"tts":"local"}'}));
  await page.route('**/api/tts',async route=>{
    const text=route.request().postDataJSON().text;spoken.push(text);
    if(text===LAUNCH_ACK&&holdAck){ackReceived();await new Promise(resolve=>{releaseAck=resolve;});}
    const pcm=Buffer.alloc(12000),wav=Buffer.alloc(44+pcm.length);wav.write('RIFF');wav.writeUInt32LE(36+pcm.length,4);wav.write('WAVEfmt ',8);wav.writeUInt32LE(16,16);wav.writeUInt16LE(1,20);wav.writeUInt16LE(1,22);wav.writeUInt32LE(24000,24);wav.writeUInt32LE(48000,28);wav.writeUInt16LE(2,32);wav.writeUInt16LE(16,34);wav.write('data',36);wav.writeUInt32LE(pcm.length,40);pcm.copy(wav,44);
    return route.fulfill({contentType:'audio/wav',body:wav});
  });
  await page.route('**/api/chat',route=>{chats++;return route.fulfill({contentType:'application/json',body:'{"text":"Test"}'});});
  await page.goto('http://localhost:5173');
  await page.locator('.start-button:enabled').waitFor({timeout:60000});
  assert.equal(await page.locator('header,.intro,footer,.scene-error').count(),0);
  assert.equal(await page.getByRole('textbox').count(),0);
  await page.screenshot({path:'qa/aina-only.png'});
  await page.evaluate(async()=>{const url=performance.getEntriesByType('resource').find(e=>new URL(e.name).pathname==='/src/speech.js')?.name||'/src/speech.js';const {Microphone}=await import(url);Microphone.prototype.start=async function(){this.requested=true;window.testMic=this;this.onStatus('listening');};});
  await page.getByRole('button',{name:'Tetapan',exact:true}).click();
  assert.equal(await page.locator('input[type=file]').count(),0);
  await page.reload();
  await page.locator('.start-button:enabled').waitFor({timeout:60000});
  await page.getByRole('button',{name:'Tetapan',exact:true}).click();
  assert.equal(await page.locator('input[type=file]').count(),0);
  await page.evaluate(async()=>{const url=performance.getEntriesByType('resource').find(e=>new URL(e.name).pathname==='/src/speech.js')?.name||'/src/speech.js';const {Microphone}=await import(url);Microphone.prototype.start=async function(){this.requested=true;window.testMic=this;this.onStatus('listening');};});
  await page.keyboard.press('Escape');
  await page.getByRole('button',{name:'Start bersama AINA'}).click();
  await page.waitForTimeout(600);
  await page.evaluate(()=>window.testMic.onFinal('Tolong launchkan'));
  assert.equal(await page.locator('.launch-reveal').count(),0,'incomplete command must not launch');
  await page.waitForTimeout(400);chats=0;
  await page.evaluate(()=>window.testMic.onFinal('Tolong launchkan ViTuTi.'));
  await acknowledgement;
  assert.equal(await page.locator('.launch-reveal').count(),0,'must finish the ViTuTi acknowledgement before flying');
  assert.equal(await page.evaluate(()=>window.jetpackStarts.length),0,'jetpack must not sound during acknowledgement');
  assert.ok(await page.locator('.reply-subtitle').innerText().then(t=>t.includes(LAUNCH_ACK)));
  // Install sampling BEFORE releasing speech: browser round trips can otherwise
  // miss the first flight frames and see only the final clamped scale.
  await page.evaluate(async()=>{
    const url=performance.getEntriesByType('resource').find(e=>new URL(e.name).pathname.endsWith('/@react-three_fiber.js'))?.name;
    if(!url)throw new Error('Real 3D renderer not loaded; do not pass on static fallback.');
    const {_roots}=await import(url);
    const canvas=document.querySelector('canvas');
    if(_roots.get(canvas).store.getState().frameloop!=='always')throw new Error('Renderer must already be running during launch speech.');
    const rig=_roots.get(canvas).store.getState().scene.getObjectByName('aina-flight-rig');
    window.flightRig=rig;
    const smoke=_roots.get(canvas).store.getState().scene.getObjectByName('aina-exhaust-smoke');
    window.exhaustSmokeSeen=false;
    window.flightSamples=[{y:rig.position.y,scale:rig.scale.x,flame:false}];
    window.smokeSeen=false;
    window.flightSampler=setInterval(()=>{if(canvas.closest('.launching'))window.flightSamples.push({y:rig.position.y,scale:rig.scale.x,flame:rig.getObjectByName('aina-rocket-exhaust').visible});if(smoke.geometry.attributes.opacity.array.some(value=>value>0))window.exhaustSmokeSeen=true;if(Number(document.querySelector('.rocket-smoke')?.dataset.particles)>0)window.smokeSeen=true;},100);
  });
  holdAck=false;releaseAck();
  await page.locator('.launch-reveal').waitFor();
  await page.locator('video').evaluate(v=>{v.loop=true;});
  assert.equal(await page.locator('video').getAttribute('src'),'/media/v2t-v4-4.mp4');
  assert.equal(await page.locator('input[type=file]').count(),0);
  const ascent=await page.evaluate(async()=>{
    await new Promise(resolve=>setTimeout(resolve,3100));clearInterval(window.flightSampler);
    return window.flightSamples;
  });
  assert.ok(ascent.length>=5,'sample actual model frames');
  assert.ok(ascent.at(-1).y-ascent[0].y>1.5,'model rises into sky rather than staying static');
  assert.ok(ascent.at(-1).scale<ascent[0].scale,'model recedes during flight');
  assert.ok(ascent.some(s=>s.flame),'rocket exhaust active during ascent');
  assert.equal(await page.evaluate(()=>window.jetpackStarts.length),1,'jetpack starts once with actual flight');
  assert.equal(await page.evaluate(()=>window.exhaustSmokeSeen),true,'smoke emitted from 3D exhaust during flight');
  assert.deepEqual(await page.evaluate(()=>{let shader=false,cone=false;window.flightRig.getObjectByName('aina-rocket-exhaust').traverse(o=>{if(o.material?.isShaderMaterial)shader=true;if(o.geometry?.type==='ConeGeometry')cone=true;});return {shader,cone};}),{shader:true,cone:false});
  assert.equal(await page.evaluate(()=>window.smokeSeen),true,'smoke rendered during the launch');
  await page.screenshot({path:'qa/smoke-transition.png'});
  await page.waitForTimeout(1050);await page.screenshot({path:'qa/rocket-lift.png'});
  await page.waitForTimeout(2300);await page.screenshot({path:'qa/smoke-reveal.png'});
  await page.locator('.launch-trail[data-covered="true"]').waitFor();
  assert.ok(await page.locator('.launch-trail').evaluate(c=>Number(c.dataset.coverage)>=.96),'white cloud covers every screen edge before video');
  assert.ok(await page.evaluate(()=>window.videoCoverGates.length>0&&window.videoCoverGates.every(Boolean)),'video playback is gated by full-screen smoke');
  assert.equal(await page.locator('video').count(),1);
  assert.equal(await page.locator('video').evaluate(v=>v.controls),false,'video has no native controls');
  assert.equal(await page.locator('.montage-play').count(),0,'no visible play button');
  assert.equal(await page.locator('.montage-close').count(),0,'only video is displayed');
  await page.locator('video').click();
  assert.deepEqual(await page.locator('video').evaluate(v=>({muted:v.muted,volume:v.volume})),{muted:false,volume:1});
  await page.waitForTimeout(1800);
  assert.ok(await page.locator('video').evaluate(v=>v.currentTime)>0);
  await page.evaluate(()=>{
    window.landingSamples=[];
    window.landingSampler=setInterval(()=>{if(document.querySelector('.avatar-canvas.landing')){const cloud=document.querySelector('.return-smoke');window.landingSamples.push({y:window.flightRig.position.y,smoke:Number(getComputedStyle(cloud).opacity),sourceY:Number(cloud.dataset.sourceY),sourceMode:cloud.dataset.sourceMode,fire:window.flightRig.getObjectByName('aina-rocket-exhaust').visible});}},100);
  });
  await page.locator('video').evaluate(v=>{v.pause();v.loop=false;v.currentTime=v.duration-2.5;});
  await page.waitForTimeout(500);
  assert.equal(await page.locator('.return-smoke').count(),0,'no smoke covers the end of the video');
  await page.locator('video').evaluate(v=>v.play());
  await page.locator('.montage-ending').waitFor();
  assert.equal(await page.locator('video').evaluate(v=>v.ended),true,'smoke waits until video fully stops');
  assert.equal(await page.locator('.return-smoke').count(),1);
  assert.equal(await page.locator('.return-smoke').getAttribute('data-covered'),'true','reverse cloud covers video before fading it');
  assert.equal(await page.locator('video').count(),1,'retain video while it slowly fades');
  assert.equal(await page.locator('.montage-reveal').evaluate(v=>getComputedStyle(v).animationDuration),'2s');
  await page.locator('.return-smoke[data-phase="veil-dissipation"]').waitFor();
  await page.waitForTimeout(1600);
  await page.screenshot({path:'qa/return-smoke-trail.png'});
  await page.locator('.launch-reveal').waitFor({state:'detached'});
  const descent=await page.evaluate(()=>{clearInterval(window.landingSampler);return window.landingSamples.filter(s=>s.y<4);});
  assert.ok(descent.length>=3,'landing is rendered, not an instant reappearance');
  assert.ok(Math.max(...descent.map(s=>s.y))-Math.min(...descent.map(s=>s.y))>.5,'visible model descends');
  assert.ok(descent.some(s=>s.sourceMode==='landing'&&s.fire&&s.smoke>0),'return cloud follows the live landing exhaust');
  assert.ok(Math.max(...descent.map(s=>s.sourceY))-Math.min(...descent.map(s=>s.sourceY))>.1,'smoke source moves with the landing nozzle');
  assert.ok(descent.at(-1).smoke<.01,'cloud dissipates before touchdown');
  await page.getByText(LANDING_MESSAGE,{exact:false}).waitFor({timeout:15000});
  assert.equal(await page.locator('.landing').count(),0,'thank-you follows landing, not descent');
  assert.ok(spoken.includes(LANDING_MESSAGE));
  await page.waitForTimeout(400);
  assert.equal(chats,0);
  await page.evaluate(()=>window.testMic.onPartial('Tolong launchkan Vi Tu Ti.'));
  await page.locator('.launch-reveal').waitFor();
  await page.keyboard.press('Escape');
  await page.locator('.launch-reveal').waitFor({state:'detached',timeout:30000});
  await page.evaluate(()=>window.testMic.onFinal('Terima kasih'));
  await page.getByText('Sama-sama, saya seronok untuk membantu anda!',{exact:false}).waitFor();
  await page.waitForTimeout(400);
  assert.ok(spoken.includes('Sama-sama, saya seronok untuk membantu anda!'));
  assert.ok(await page.evaluate(()=>Math.abs(window.playedRates.at(-1)-1.10)<.001),'thank-you uses the joyful delivery');
  assert.equal(chats,0);
  await page.setViewportSize({width:390,height:844});await page.screenshot({path:'qa/aina-only-mobile.png'});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  assert.deepEqual(errors,[]);
  console.log(`PASS: unmuted full-volume video and blocked-autoplay play button; full ViTuTi command, acknowledgement before take-off; 3D ascent ${ascent[0].y.toFixed(2)} → ${ascent.at(-1).y.toFixed(2)}, smoke, video ends, landing then thank-you, no upload picker or browser errors.`);
}finally{await browser.close();}
