import { chromium } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
import assert from 'node:assert/strict';
await mkdir('qa',{recursive:true});
const browser = await chromium.launch({headless:true,args:['--use-angle=d3d11']});
const page = await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://localhost:5173');
await page.getByRole('button',{name:'Start bersama AINA'}).waitFor();
await page.waitForFunction(()=>!document.querySelector('.start-button')?.disabled,{timeout:60000});
await page.waitForTimeout(2000);
await page.screenshot({path:'qa/desktop.png'});
await page.evaluate(async()=>{ const {motion}=await import('/src/speech.js');Object.assign(motion,{speaking:true,open:1,round:0,wide:0}); });
await page.waitForTimeout(1000);
await page.screenshot({path:'qa/mouth-open.png'});
await page.evaluate(async()=>{ const {motion}=await import('/src/speech.js');Object.assign(motion,{speaking:false,open:0,round:0,wide:0}); });
assert.equal(await page.getByRole('textbox').count(),0,'voice-only UI has no chatbox');
await page.getByRole('button',{name:'Tetapan',exact:true}).click();
await page.getByRole('complementary',{name:'Tetapan',exact:true}).waitFor();
await page.getByRole('button',{name:'Sisi',exact:true}).click();
await page.waitForTimeout(1000);await page.screenshot({path:'qa/side.png'});
await page.getByRole('button',{name:'Belakang',exact:true}).click();
await page.waitForTimeout(1000);await page.screenshot({path:'qa/back.png'});
await page.getByRole('button',{name:'Depan',exact:true}).click();
await page.keyboard.press('Escape');
assert.equal(await page.getByRole('complementary',{name:'Tetapan',exact:true}).count(),0);
await page.getByRole('button',{name:'AINA melambai'}).click();
await page.waitForTimeout(1800);await page.screenshot({path:'qa/wave.png'});
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:'qa/mobile.png',fullPage:true});
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
assert.deepEqual(errors,[]);
console.log('PASS: fitted GLB, glossy helmet, mouth geometry, wave, front/side/back, desktop/mobile, voice-only UI, settings keyboard, no page errors.');
await browser.close();
